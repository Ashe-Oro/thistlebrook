// OWNER: grok-roads lane. Writes docs/ROAD-AUDIT.md from two audit JSON files.
// Usage: node tools/road-audit-report.mjs <before.json> <after.json> [sim-before.json sim-after.json]
import {readFileSync, writeFileSync} from 'node:fs';
const [beforeFile, afterFile, simBefore, simAfter] = process.argv.slice(2);
const before = JSON.parse(readFileSync(beforeFile)), after = JSON.parse(readFileSync(afterFile));
const sims = simBefore && simAfter ? [JSON.parse(readFileSync(simBefore)), JSON.parse(readFileSync(simAfter))] : null;
const cats = [...new Set([...Object.keys(before.summary), ...Object.keys(after.summary)])].sort();
const row = (f) => `| ${f.id} | ${f.category} | (${f.at.join(', ')}) | ${f.count} | ${f.detail.replaceAll('|', '/')} | ${f.status}${f.reason ? ': ' + f.reason : ''} | ${f.shot ? `[crop](../${f.shot})` : ''} |`;
let md = `# Road audit (seed 831)

Generated by \`node tools/audit-roads.mjs --json … --shots\` and \`node tools/road-audit-report.mjs\`.
"Before" is the base commit \`7c6d639\`; "after" is \`village/grok-roads\`. Coordinates are world x, z in metres.
Each finding links a plan-view crop (red ring = open, blue = justified). \`count\` is how many samples fall in that 10 m cluster.

## Summary

| Category | Before open | Before justified | After open | After justified |
| --- | ---: | ---: | ---: | ---: |
${cats.map((c) => `| ${c} | ${before.summary[c]?.open ?? 0} | ${before.summary[c]?.justified ?? 0} | ${after.summary[c]?.open ?? 0} | ${after.summary[c]?.justified ?? 0} |`).join('\n')}
| **total** | **${before.findings.filter((f) => f.status === 'open').length}** | ${before.findings.filter((f) => f.status !== 'open').length} | **${after.findings.filter((f) => f.status === 'open').length}** | ${after.findings.filter((f) => f.status !== 'open').length} |

Walk network: before ${before.walkNodes} nodes / ${before.crossings} crossings (built by the same tool over the old roads; residents did not use it then), after ${after.walkNodes} nodes / ${after.crossings} crossings.
`;
if (sims) md += `
## Full-day collision simulation (\`node tools/sim-collisions.mjs\`, seed 831, 24 game hours, 0.2 s steps)

| Events (samples) | Before | After |
| --- | ---: | ---: |
${['carCar', 'carPerson', 'personOnRoad', 'unsafeCrossing'].map((k) => `| ${k} | ${sims[0].counts[k]} (${sims[0].unique[k]} distinct) | ${sims[1].counts[k]} (${sims[1].unique[k]} distinct) |`).join('\n')}
| samples | ${sims[0].counts.samples} | ${sims[1].counts.samples} |
`;
md += `
## After: remaining findings (all justified)

| id | category | at | count | detail | status | shot |
| --- | --- | --- | ---: | --- | --- | --- |
${after.findings.map(row).join('\n')}

## Before: findings on the base commit

| id | category | at | count | detail | status | shot |
| --- | --- | --- | ---: | --- | --- | --- |
${before.findings.map(row).join('\n')}
`;
writeFileSync(new URL('../docs/ROAD-AUDIT.md', import.meta.url), md);
console.log('wrote docs/ROAD-AUDIT.md', before.findings.length, after.findings.length);
